package main.dao;

import main.models.Cart;
import main.models.Device;
import main.models.User;

/**
 * Интерфейс CartService определяет операции для работы с корзинами покупок пользователей.
 * Предоставляет методы для управления товарами в корзине и получения информации о корзине.
 */
public interface CartService {
    /**
     * Получает корзину для указанного пользователя.
     * Если у пользователя еще нет корзины, создает новую.
     * @param user пользователь, чью корзину нужно получить
     * @return корзина пользователя
     */
    Cart getCartForUser(User user);

    /**
     * Добавляет устройство в корзину пользователя.
     * @param user пользователь, в чью корзину добавляется устройство
     * @param device устройство, которое нужно добавить
     */
    void addToCart(User user, Device device);

    /**
     * Удаляет устройство из корзины пользователя.
     * @param user пользователь, из чьей корзины удаляется устройство
     * @param device устройство, которое нужно удалить
     */
    void removeFromCart(User user, Device device);

    /**
     * Очищает корзину пользователя от всех товаров.
     * @param user пользователь, чью корзину нужно очистить
     */
    void clearCart(User user);

    /**
     * Возвращает общую стоимость всех товаров в корзине пользователя.
     * @param user пользователь, для которого нужно посчитать стоимость корзины
     * @return общая стоимость корзины
     */
    double getCartTotal(User user);
}
